// scripts/lib/pwa-manifest.js
// Single source of truth for the installable app's web app manifest.
//
// `vite.config.js` hands this object to `VitePWA`, which emits
// `dist/manifest.webmanifest` and injects `<link rel="manifest">` into the
// built `index.html`. `scripts/lib/pwa-manifest.test.js` asserts the install
// contract (start_url '/home', standalone display, 192/512 icons) directly
// against these constants, so the contract is testable without running a
// production build.
//
// Chrome's install criteria (web.dev/articles/install-criteria, updated
// 2024-09-19) require: HTTPS, `name`/`short_name`, a 192px and a 512px icon,
// `start_url`, a `display` of standalone/fullscreen/minimal-ui, and
// `prefer_related_applications` absent or false. A service worker with a fetch
// handler is NOT required to be installable any more, so the generated service
// worker (see `vite.config.js`) only exists to precache the app shell.
//
// The installed app opens on the user dashboard `/home` (the public homepage
// `/` is a marketing/share-code page), so `start_url` is `/home` while `scope`
// stays `/` so ordinary in-app navigation still stays inside the PWA window.

export const START_URL = '/home';
export const APP_SCOPE = '/';
// Stable app identity: the origin root, independent of `start_url`, so
// changing the launch page later does not register as a different app.
export const APP_ID = '/';
export const APP_NAME = 'UFF English';
export const APP_SHORT_NAME = 'UFF';
export const APP_DESCRIPTION =
    'Practice speaking English with voice-first video lessons and get instant feedback. Free, any level.';
export const APP_LANG = 'en';
export const APP_CATEGORIES = ['education'];
// The app shell is dark navy (`#0b1a2a`, see `src/assets/css/app.css`), so the
// launcher theme, the install splash background and the icon background all
// match it. The white UFF mark is flattened onto this colour by
// `pwa-assets.config.js` so the icons stay legible on a light launcher.
export const THEME_COLOR = '#0b1a2a';
export const BACKGROUND_COLOR = '#0b1a2a';

// Generated by `npm run pwa:assets` (`pwa-assets.config.js`) into `public/`
// from `public/pwa-icon-source.png` (the lossless conversion of the app's
// existing brand favicon). 64/192/512 are `any` (flattened, transparent-safe),
// 512 `maskable` is the Android adaptive icon with the extra safe zone.
// `apple-touch-icon-180x180.png`/`favicon.ico` are head links, not manifest
// entries.
export const PWA_ICONS = [
    { src: '/pwa-64x64.png', sizes: '64x64', type: 'image/png', purpose: 'any' },
    { src: '/pwa-192x192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: '/pwa-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: '/maskable-icon-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
];

/**
 * Install-dialog screenshots: real captures of lesson `a` of the
 * `wouldyourather` course (the friend-practice lesson), driven through
 * Playwright against the running app. `sizes` must match the real pixel
 * dimensions or Chrome ignores the entry. `@khmyznikov/pwa-install` reads
 * these for its "More" gallery and Chrome uses them in its own install UI —
 * there is no attribute for screenshots, they are manifest-only.
 *
 * Regenerate by loading /course/wouldyourather/lesson/a, dismissing the
 * guest modal, starting the intro video so the "INCOMING VIDEO" label
 * clears, then clipping to #root (never to fixed viewport coordinates).
 */
export const PWA_SCREENSHOTS = [
    {
        src: '/pwa-screenshot-narrow.png',
        sizes: '720x1280',
        type: 'image/png',
        form_factor: 'narrow',
        label: 'Practise speaking with your friend',
    },
    {
        src: '/pwa-screenshot-wide.png',
        sizes: '1280x800',
        type: 'image/png',
        form_factor: 'wide',
        label: 'Practise speaking with your friend',
    },
];

/**
 * The web app manifest. Keep it a plain function of the constants above so
 * tests can assert the exact object the build emits.
 */
export function buildPwaManifest() {
    return {
        id: APP_ID,
        name: APP_NAME,
        short_name: APP_SHORT_NAME,
        description: APP_DESCRIPTION,
        start_url: START_URL,
        scope: APP_SCOPE,
        display: 'standalone',
        theme_color: THEME_COLOR,
        background_color: BACKGROUND_COLOR,
        lang: APP_LANG,
        dir: 'ltr',
        categories: APP_CATEGORIES,
        icons: PWA_ICONS,
        screenshots: PWA_SCREENSHOTS,
        // Chrome's criteria: must be absent or false for the install prompt.
        prefer_related_applications: false,
    };
}
