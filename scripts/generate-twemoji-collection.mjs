#!/usr/bin/env node
// Build the full Twemoji file manifest used by the in-app emoji picker.
// The picker renders the pinned CDN SVGs; this file only lists their codes and
// the category/name metadata that makes browsing possible.
//
// Run: `node scripts/generate-twemoji-collection.mjs`

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(REPO_ROOT, 'src', 'generated', 'twemoji-emojis.js');
const VERSION = '15.0.3';
const DATA_VERSION = '15.1.2';

const CATEGORY_ORDER = [
    'Smileys & Emotion',
    'People & Body',
    'Animals & Nature',
    'Food & Drink',
    'Travel & Places',
    'Activities',
    'Objects',
    'Symbols',
    'Flags',
    'Component',
    'Other',
];

function walkFiles(items, out = []) {
    for (const item of items) {
        if (item.type === 'file' && item.name.endsWith('.svg')) out.push(item.name.slice(0, -4));
        else if (item.type === 'directory') walkFiles(item.files, out);
    }
    return out;
}

function candidates(unified) {
    const raw = String(unified || '').toLowerCase();
    if (!raw) return [];
    const stripZeros = (code) => code.split('-').map((part) => {
        if (part === 'fe0f') return part;
        const n = parseInt(part, 16);
        return Number.isFinite(n) ? n.toString(16) : part;
    }).join('-');
    const set = new Set([raw, raw.replace(/-fe0f/g, '')]);
    set.add(stripZeros(raw));
    set.add(stripZeros(raw.replace(/-fe0f/g, '')));
    return [...set];
}

async function main() {
    const pkg = await (await fetch(`https://data.jsdelivr.com/v1/packages/gh/jdecked/twemoji@${VERSION}`)).json();
    const fileSet = new Set(walkFiles(pkg.files));
    const data = await (await fetch(`https://cdn.jsdelivr.net/npm/emoji-datasource@${DATA_VERSION}/emoji.json`)).json();

    const byCode = new Map();
    for (const entry of data) {
        const code = candidates(entry.unified).find((c) => fileSet.has(c));
        if (!code || byCode.has(code)) continue;
        byCode.set(code, {
            code,
            name: entry.name || entry.short_name || code,
            category: CATEGORY_ORDER.includes(entry.category) ? entry.category : 'Other',
        });
    }
    for (const code of fileSet) {
        if (!byCode.has(code)) byCode.set(code, { code, name: code, category: 'Other' });
    }

    const rows = [...byCode.values()].sort((a, b) => {
        const ca = CATEGORY_ORDER.indexOf(a.category);
        const cb = CATEGORY_ORDER.indexOf(b.category);
        if (ca !== cb) return ca - cb;
        return a.name.localeCompare(b.name);
    });

    const categories = CATEGORY_ORDER.filter((c) => rows.some((r) => r.category === c));
    const body = `// Generated by scripts/generate-twemoji-collection.mjs — do not edit by hand.
// Twemoji ${VERSION} (CC-BY 4.0). Source: https://github.com/jdecked/twemoji
export const TWEMOJI_CATEGORIES = ${JSON.stringify(categories)};

export const TWEMOJI_EMOJIS = ${JSON.stringify(rows)};
`;
    fs.writeFileSync(OUT, body);
    console.log(`wrote ${rows.length} emoji across ${categories.length} categories -> ${path.relative(REPO_ROOT, OUT)}`);
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (invokedDirectly) main().catch((e) => { console.error('ERROR:', e.message); process.exit(1); });
