#!/usr/bin/env node
// Generates lessonId posters (640w jpg + LQIP) from the introBackgroundVideoUrl
// mp4 at 0.2s. Source videos are downloaded from R2 (the authoring CDN) into a
// temp cache, so no local video files are required.
//
// Usage:
//   node scripts/generate-thumbnails.mjs                # generate + write LQIP module
//   node scripts/generate-thumbnails.mjs --upload       # upload existing posters to R2 (no generate)
//   node scripts/generate-thumbnails.mjs --check        # exit non-zero if any poster missing
//   node scripts/generate-thumbnails.mjs --video-dir=X  # prefer local mp4s over R2 download
//
// Requires ffmpeg on PATH for generation. --upload uses wrangler r2 object put
// (needs authenticated wrangler or CLOUDFLARE_API_TOKEN + CLOUDFLARE_ACCOUNT_ID env).
//
// New-video flow: upload the intro mp4 to R2 assets/videos/<slug>.mp4 and add a
// lesson referencing it in src/config/model.json. Then either run this script
// (generate + --upload) or just push — deploy.yml runs generate/upload/verify
// automatically before build.

import { execFile } from 'node:child_process';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const MODEL_PATH = path.join(ROOT, 'src/config/model.json');
const POSTERS_DIR = path.join(ROOT, 'public/assets/posters');
const GENERATED_PATH = path.join(ROOT, 'src/generated/poster-lqips.js');
const CDN_VIDEO_BASE = 'https://r2.ultrafastfluency.com/assets/videos/';

function run(bin, args) {
  return new Promise((resolve, reject) => {
    execFile(bin, args, { maxBuffer: 64 * 1024 * 1024 }, (err, stdout, stderr) => {
      if (err) { err.stderr = stderr; return reject(err); }
      resolve(stdout);
    });
  });
}

async function loadModel() {
  return JSON.parse(await fs.readFile(MODEL_PATH, 'utf8'));
}

// Lessons that need a poster — only those whose first step is a lesson intro.
function introLessons(lessons) {
  return lessons.filter(l => l.steps?.[0]?.introBackgroundVideoUrl);
}

async function ensureFfmpeg() {
  try {
    await run('ffmpeg', ['-version']);
    await run('ffprobe', ['-version']);
  } catch {
    console.error('ERROR: ffmpeg and ffprobe are required on PATH.\n  Install:  sudo apt-get install -y ffmpeg   (macOS: brew install ffmpeg)');
    process.exit(1);
  }
}

async function resolveSource(slug, videoDir) {
  // 1) Local dir if provided/committed
  if (videoDir) {
    const local = path.join(videoDir, `${slug}.mp4`);
    try { await fs.stat(local); return local; } catch {}
  }
  const repoLocal = path.join(ROOT, 'public/assets/videos', `${slug}.mp4`);
  try { await fs.stat(repoLocal); return repoLocal; } catch {}

  // 2) Download from R2 (source of truth)
  const cacheDir = path.join(os.tmpdir(), 'uff-posters-cache');
  await fs.mkdir(cacheDir, { recursive: true });
  const cached = path.join(cacheDir, `${slug}.mp4`);
  try {
    await fs.stat(cached);
    console.log(`CACHE hit ${slug}.mp4`);
    return cached;
  } catch {}

  console.log(`DOWNLOAD ${slug}.mp4 from R2…`);
  const res = await fetch(`${CDN_VIDEO_BASE}${slug}.mp4`);
  if (!res.ok) throw new Error(`download failed HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  await fs.writeFile(cached, buf);
  return cached;
}

async function generateOne(lessonId, slug, videoDir) {
  const src = await resolveSource(slug, videoDir);
  const outJpg = path.join(POSTERS_DIR, `${lessonId}.jpg`);
  const lqipPath = path.join(POSTERS_DIR, `${lessonId}.lqip.jpg`);

  const srcStat = await fs.stat(src);
  let outStat = null;
  try { outStat = await fs.stat(outJpg); } catch {}

  // Skip re-extract if poster is newer than source.
  if (outStat && outStat.mtimeMs > srcStat.mtimeMs) {
    console.log(`SKIP ${lessonId} (up-to-date)`);
  } else {
    console.log(`GEN ${lessonId}: ${slug}.mp4 @0.2s -> ${lessonId}.jpg`);
    await run('ffmpeg', ['-y', '-loglevel', 'error', '-ss', '0.2', '-i', src, '-vframes', '1', '-vf', 'scale=640:-2', '-q:v', '4', outJpg]);
  }

  await run('ffmpeg', ['-y', '-loglevel', 'error', '-ss', '0.2', '-i', src, '-vframes', '1', '-vf', 'scale=32:-2', '-q:v', '15', lqipPath]);
  const b64 = (await fs.readFile(lqipPath)).toString('base64');
  await fs.unlink(lqipPath).catch(() => {});
  return { lessonId, dataUri: `data:image/jpeg;base64,${b64}` };
}

async function writeGenerated(lqips) {
  const entries = Object.entries(lqips)
    .map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n');
  const content = `// Auto-generated by scripts/generate-thumbnails.mjs — do not hand-edit.
export const POSTER_LQIPS = {
${entries}
};

export function getPosterLqip(lessonId) {
    return POSTER_LQIPS[lessonId] || null;
}
`;
  await fs.writeFile(GENERATED_PATH, content, 'utf8');
  console.log(`Wrote ${GENERATED_PATH} (${Object.keys(lqips).length} entries)`);
}

async function wranglerMajor() {
  try {
    const out = await run('npx', ['wrangler', '--version']);
    const m = /(?:wrangler\s+)?(\d+)\./.exec(out);
    return m ? parseInt(m[1], 10) : 0;
  } catch {
    return 0;
  }
}

async function uploadAll(lessons) {
  const targets = introLessons(lessons);
  if (!process.env.CLOUDFLARE_API_TOKEN) {
    console.warn('WARN: CLOUDFLARE_API_TOKEN not set — upload will likely fail (run `wrangler login` or export the token).');
  }
  // wrangler >=4 targets the LOCAL R2 emulator by default and needs --remote;
  // wrangler 3.x is remote-only and rejects the --remote flag.
  const major = await wranglerMajor();
  const remoteArg = major >= 4 ? '--remote' : null;
  console.log(`Uploading ${targets.length} poster(s) to R2 (wrangler ${major || '?'})…`);
  let failed = 0;
  for (const l of targets) {
    const file = path.join(POSTERS_DIR, `${l.lessonId}.jpg`);
    try { await fs.stat(file); } catch {
      console.error(`UPLOAD FAIL ${l.lessonId}: ${l.lessonId}.jpg not generated yet — run generate first`);
      failed++; continue;
    }
    try {
      const args = ['wrangler', 'r2', 'object', 'put'];
      if (remoteArg) args.push(remoteArg);
      args.push(`uff/assets/posters/${l.lessonId}.jpg`, '--file', file, '--content-type', 'image/jpeg');
      await run('npx', args);
      console.log(`UPLOAD ${l.lessonId}.jpg`);
    } catch (e) {
      console.error(`UPLOAD FAIL ${l.lessonId}:`, e.message);
      failed++;
    }
  }
  // Non-fatal: a poster-upload failure must NOT block the app deploy. The
  // app degrades gracefully (LQIP -> video frame reveal) when a poster is
  // missing on R2, and the separate verify step still gates the build on
  // locally generated posters.
  if (failed) {
    console.warn(`--upload: ${failed}/${targets.length} poster uploads failed. ` +
      'The app still works (LQIP/gradient fallback). Check the R2 permission on your ' +
      'CLOUDFLARE_API_TOKEN (needs Account > Workers R2 Storage > Edit).');
  }
}

async function main() {
  const check = process.argv.includes('--check');
  const upload = process.argv.includes('--upload');
  const videoDirArg = process.argv.find(a => a.startsWith('--video-dir'));
  const videoDir = videoDirArg ? videoDirArg.split('=')[1] : undefined;

  const model = await loadModel();
  const lessons = model.lessons || [];
  const introLessonsList = introLessons(lessons);

  if (upload) {
    await uploadAll(lessons);
    return;
  }

  if (check) {
    let missing = 0;
    for (const l of introLessonsList) {
      try { await fs.stat(path.join(POSTERS_DIR, `${l.lessonId}.jpg`)); }
      catch { console.error(`MISSING poster for lesson ${l.lessonId} (intro: ${l.steps[0].introBackgroundVideoUrl})`); missing++; }
    }
    try { await fs.stat(GENERATED_PATH); } catch { console.error('Missing src/generated/poster-lqips.js'); missing++; }
    if (missing) { console.error(`--check failed: ${missing} missing. Run \`node scripts/generate-thumbnails.mjs\` to generate.`); process.exit(1); }
    console.log(`--check OK: ${introLessonsList.length} intro lessons have posters`);
    return;
  }

  await ensureFfmpeg();
  await fs.mkdir(POSTERS_DIR, { recursive: true });
  await fs.mkdir(path.dirname(GENERATED_PATH), { recursive: true });
  const lqips = {};
  for (const lesson of introLessonsList) {
    const slug = lesson.steps[0].introBackgroundVideoUrl;
    try {
      const res = await generateOne(lesson.lessonId, slug, videoDir);
      if (res) lqips[res.lessonId] = res.dataUri;
    } catch (e) {
      console.error(`ERROR ${lesson.lessonId} (${slug}):`, e.message, '\n  Ensure the video is uploaded to R2 as assets/videos/<slug>.mp4');
    }
  }
  await writeGenerated(lqips);
  console.log('\nPosters ready. Publish to R2 with: node scripts/generate-thumbnails.mjs --upload');
}

main().catch(e => { console.error(e); process.exit(1); });