// src/modules/lesson/lesson-not-found-logic.js
// Pure rules that tell a DEAD LINK apart from a TECHNICAL FAILURE on the
// lesson route.
//
// A dead link is a link whose course or lesson no longer exists: the course
// config was retired (or renamed), or the lesson id in the URL is gone. The app
// answers it with the real "not found" page (`src/components/NotFoundPage.jsx`),
// whose copy says the link may no longer be active and which offers the course
// list. That is the truth for a retired lesson link.
//
// A technical failure is anything else — the network is down, the response is
// unreadable — and keeps the critical-error screen, whose "check your internet
// connection" message is the right one there.
//
// No DOM, no browser globals, no data access — fully unit-testable.

/** The outcome of a course-config fetch. */
export const COURSE_CONFIG_OUTCOME = {
    ready: 'ready',
    missing: 'missing',
};

/**
 * Classify a course-config response as "the course is there" or "the course is
 * gone".
 *
 * Cloudflare Pages rewrites EVERY path to the SPA shell (`public/_redirects`:
 * `/*  /index.html  200`), so a config that does not exist comes back as
 * 200 text/html — the app shell, not a config. A dev server answers 404 with
 * its own HTML error page. Either way the body is not a config: the course is
 * gone. Only a JSON body (or a JSON content-type) means the course is there.
 *
 * @param {{ok?: boolean, contentType?: string, body?: string|null}} response
 * @returns {'ready'|'missing'}
 */
export function classifyCourseConfigResponse({ ok = false, contentType = '', body = null } = {}) {
    if (!ok) return COURSE_CONFIG_OUTCOME.missing;
    const type = String(contentType || '').toLowerCase();
    if (type.includes('json')) return COURSE_CONFIG_OUTCOME.ready;
    // No JSON content-type: fall back to the body. A config served with a
    // wrong content-type still parses as JSON; the SPA shell never does.
    const text = typeof body === 'string' ? body.trimStart() : '';
    if (text.startsWith('{') || text.startsWith('[')) return COURSE_CONFIG_OUTCOME.ready;
    return COURSE_CONFIG_OUTCOME.missing;
}

/**
 * Whether the lesson id is gone from the course config.
 *
 * A friend link records the lesson the visitor should record next; the course
 * configs are regenerated by the config bot, so that id can disappear while
 * the link is still being handed out. Such a link is dead, not broken.
 *
 * @param {object|null|undefined} configData
 * @param {string} lessonId
 * @returns {boolean} true only when the config has lessons and none of them is
 *   the requested one.
 */
export function isLessonMissingFromConfig(configData, lessonId) {
    const lessons = configData?.lessons;
    if (!Array.isArray(lessons)) return false; // no config → no verdict
    if (typeof lessonId !== 'string' || lessonId === '') return false;
    return !lessons.some((lesson) => lesson?.lessonId === lessonId);
}

// The flag that marks an error as "the link is dead". Kept as a constant so
// the marker and the reader cannot drift apart.
export const NOT_FOUND_FLAG = 'notFound';

/**
 * Tag an error as a dead link. The message is kept: it names the course or
 * lesson that is gone, which is what the log and the analytics event report.
 *
 * @template {Error|object} T
 * @param {T} error
 * @returns {T} the same error, tagged.
 */
export function markNotFoundError(error) {
    if (error && typeof error === 'object') error[NOT_FOUND_FLAG] = true;
    return error;
}

/**
 * Whether an error means "the link is dead" (show the not-found page) rather
 * than "something broke" (show the critical-error screen).
 *
 * @param {unknown} error
 * @returns {boolean}
 */
export function isNotFoundError(error) {
    return !!error && typeof error === 'object' && error[NOT_FOUND_FLAG] === true;
}
